"""Contract for `--check` and for idempotent regeneration.

These two together are the difference between a generator that is useful for one
month and a fleet-management capability that stays useful. If you build only one
feature beyond the minimum, build `--check`.
"""

from __future__ import annotations

import pytest

from scaffolder.check import check_drift, drift_exit_code, read_stamp
from scaffolder.generate import write_files, write_stamp
from scaffolder.models import GENERATED_MARKER, DriftKind, RenderedFile
from scaffolder.render import render_template


def _generate(template_dir, spec, target, version) -> list[RenderedFile]:
    rendered = render_template(template_dir, spec, version)
    write_files(target, rendered)
    write_stamp(target, spec, version)
    return rendered


class TestStamp:
    def test_the_stamp_records_the_template_version(
        self, fastapi_template, spec, tmp_path, version
    ):
        """Without this you cannot answer "which services have the old CI
        config?", and answering that is the entire long-term value of the tool."""
        _generate(fastapi_template, spec, tmp_path, version)
        assert read_stamp(tmp_path).version == version.version

    def test_an_unscaffolded_directory_is_recognised_as_such(self, tmp_path):
        """ "This directory was not generated by scaffolder" is the useful message.

        Reporting every file as drifted is technically true and completely
        useless, and it is what you get by default.
        """
        (tmp_path / "some-other-repo").mkdir()
        with pytest.raises(FileNotFoundError):
            read_stamp(tmp_path / "some-other-repo")

    def test_the_stamp_is_written_last(self, fastapi_template, spec, tmp_path, version):
        """A crash partway through generation must leave a directory `--check`
        refuses to interpret, not one it misreads as fully drifted."""
        raise AssertionError("implement: make write_files fail midway, assert no stamp exists")


class TestDriftDetection:
    def test_a_freshly_generated_service_has_no_drift(
        self, fastapi_template, spec, tmp_path, version
    ):
        rendered = _generate(fastapi_template, spec, tmp_path, version)
        findings = check_drift(tmp_path, rendered)
        assert [f for f in findings if f.kind is not DriftKind.UP_TO_DATE] == []

    def test_a_file_the_template_added_is_reported_missing(
        self, fastapi_template, spec, tmp_path, version
    ):
        """The most common and most actionable finding: a file added to the
        template after this service was generated."""
        rendered = _generate(fastapi_template, spec, tmp_path, version)
        (tmp_path / "Dockerfile").unlink()
        findings = check_drift(tmp_path, rendered)
        assert any(f.kind is DriftKind.MISSING and f.path == "Dockerfile" for f in findings)

    def test_an_edited_generated_file_is_reported_modified(
        self, fastapi_template, spec, tmp_path, version
    ):
        rendered = _generate(fastapi_template, spec, tmp_path, version)
        (tmp_path / "Dockerfile").write_text(f"# {GENERATED_MARKER}\nFROM scratch\n")
        findings = check_drift(tmp_path, rendered)
        assert any(f.kind is DriftKind.MODIFIED for f in findings)

    def test_hand_written_files_are_never_reported(self, fastapi_template, spec, tmp_path, version):
        """Team-owned files are out of scope by definition. Reporting a
        hand-written `main.py` as drifted buries the one finding that matters
        under twenty that do not."""
        rendered = _generate(fastapi_template, spec, tmp_path, version)
        main = tmp_path / "src" / "payments_api" / "main.py"
        main.write_text("# completely rewritten by the team\n")
        findings = check_drift(tmp_path, rendered)
        assert not any("main.py" in f.path for f in findings)

    def test_trailing_whitespace_and_line_endings_are_normalised(
        self, fastapi_template, spec, tmp_path, version
    ):
        """Otherwise every service checked out on Windows reports total drift,
        and the report becomes noise within a week."""
        rendered = _generate(fastapi_template, spec, tmp_path, version)
        dockerfile = tmp_path / "Dockerfile"
        dockerfile.write_bytes(dockerfile.read_text().replace("\n", "\r\n").encode())
        findings = check_drift(tmp_path, rendered)
        assert not any(f.kind is DriftKind.MODIFIED for f in findings)

    def test_up_to_date_files_are_omitted_by_default(
        self, fastapi_template, spec, tmp_path, version
    ):
        """A report listing forty up-to-date files and two problems has hidden
        the two problems."""
        rendered = _generate(fastapi_template, spec, tmp_path, version)
        (tmp_path / "Dockerfile").unlink()
        findings = check_drift(tmp_path, rendered)
        assert all(f.kind is not DriftKind.UP_TO_DATE for f in findings)

    def test_exit_code_is_nonzero_on_drift(self, fastapi_template, spec, tmp_path, version):
        """So this runs nightly in CI across 23 repositories. Run by a human once
        it is a curiosity; run on a schedule it is fleet management."""
        rendered = _generate(fastapi_template, spec, tmp_path, version)
        (tmp_path / "Dockerfile").unlink()
        assert drift_exit_code(check_drift(tmp_path, rendered)) == 1

    def test_exit_code_is_zero_when_clean(self, fastapi_template, spec, tmp_path, version):
        rendered = _generate(fastapi_template, spec, tmp_path, version)
        assert drift_exit_code(check_drift(tmp_path, rendered)) == 0

    def test_a_stale_stamp_distinguishes_template_moved_from_file_edited(self):
        """You cannot tell these apart from the file alone, and they need opposite
        responses: one is "regenerate", the other is "talk to whoever edited it".

        Stamp behind current -> the template moved on.
        Stamp equal to current -> somebody edited the file.
        """
        raise AssertionError(
            "implement: generate at 1.0.0, check against 1.1.0, assert the message"
        )


class TestIdempotentRegeneration:
    def test_regeneration_overwrites_marked_files(self, fastapi_template, spec, tmp_path, version):
        raise AssertionError("implement: edit a marked file, regenerate, assert it is restored")

    def test_regeneration_preserves_hand_written_files(
        self, fastapi_template, spec, tmp_path, version
    ):
        """The acceptance criterion, and the failure that would make people stop
        trusting the tool permanently."""
        _generate(fastapi_template, spec, tmp_path, version)
        main = tmp_path / "src" / "payments_api" / "main.py"
        main.write_text("# the team's actual service\n")
        rendered = render_template(fastapi_template, spec, version)
        write_files(tmp_path, rendered, overwrite_generated=True)
        assert main.read_text() == "# the team's actual service\n"

    def test_a_file_whose_marker_was_removed_is_not_clobbered(
        self, fastapi_template, spec, tmp_path, version
    ):
        """The subtle one.

        The template says this file is generated, but the copy on disk has no
        marker - somebody took ownership, deliberately or by accident. Either way
        the tool is not entitled to clobber it. Skip it and report it.
        """
        _generate(fastapi_template, spec, tmp_path, version)
        dockerfile = tmp_path / "Dockerfile"
        dockerfile.write_text("FROM scratch  # marker deliberately removed\n")
        rendered = render_template(fastapi_template, spec, version)
        write_files(tmp_path, rendered, overwrite_generated=True)
        assert "FROM scratch" in dockerfile.read_text()
