"""`--check`: how far has an existing service drifted from its template?

**Build this one even if you build nothing else beyond the minimum.** A generator
is useful for a month, after which everything has already been generated. The
check mode is what turns it into an ongoing fleet-management capability, and it
is the part most people never write.

YOUR JOB: implement `check_drift` and `read_stamp`.
"""

from __future__ import annotations

from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from pathlib import Path

    from scaffolder.models import DriftFinding, RenderedFile, TemplateVersion


def read_stamp(service_dir: Path) -> TemplateVersion:
    """Read `.scaffolder.yaml` to learn which template version made this service.

    Raises:
        FileNotFoundError: not a scaffolded service. The caller turns this into
            "this directory was not generated by scaffolder" rather than
            reporting every file as drifted - the second message is technically
            true and completely useless.
    """
    raise NotImplementedError


def check_drift(
    service_dir: Path,
    rendered: list[RenderedFile],
) -> list[DriftFinding]:
    """Compare a service on disk against what the current template produces.

    Only `generated=True` files are compared. Team-owned files are out of scope
    by definition - reporting a hand-written `main.py` as drifted would bury the
    one finding that matters under twenty that do not.

    The four outcomes:

        MISSING      the template emits it, the service does not have it. Usually
                     a file added to the template after this service was made -
                     the most common and most actionable finding.
        MODIFIED     contents differ. Either the template moved on, or somebody
                     edited a generated file. **You cannot tell which from the
                     file alone**, which is what the stamped version is for:
                     stamp behind current means "template moved on", stamp equal
                     to current means "somebody edited it".
        EXTRA        the service has a marked file the template no longer emits.
                     A removal the service never got.
        UP_TO_DATE   identical.

    Normalise trailing whitespace and line endings before comparing, or every
    service checked out on Windows reports total drift.

    Return findings sorted with the actionable ones first and `UP_TO_DATE`
    omitted unless asked - a report that lists forty up-to-date files and two
    problems has hidden the two problems.
    """
    raise NotImplementedError


def drift_exit_code(findings: list[DriftFinding]) -> int:
    """0 when nothing is drifted, 1 when something is.

    Non-zero on drift so this can run in CI across every repo on a schedule,
    which is the point: `--check` run by a human once is a curiosity, run nightly
    across 23 services it is fleet management.
    """
    raise NotImplementedError


